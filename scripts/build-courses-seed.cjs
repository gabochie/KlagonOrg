// Builds an idempotent SQL migration from the Klagon Courses source folder.
// Each lesson becomes a base64-encoded markdown blob upserted against
// (course_id, sort_order), safe for any special characters.
const fs = require("fs");
const path = require("path");

const COURSES_ROOT = path.resolve(
  "C:/Users/user/Desktop/GABOCHIE CORP/KLAGON OPERATIONS/Klagon Courses",
);
const OUT_FILE = path.resolve("supabase/migrations/20260916120000_seed_all_courses_content.sql");

function esc(value) {
  return String(value).replace(/'/g, "''");
}

function estimateDuration(words) {
  const d = Math.round(words / 90) + 3;
  if (d < 8) return 8;
  if (d > 18) return 18;
  return d;
}

const manifest = JSON.parse(
  fs.readFileSync(path.join(COURSES_ROOT, "manifest.json"), "utf8"),
);

const blocks = [];
blocks.push("-- Auto-generated by scripts/build-courses-seed.cjs. Do not edit by hand.");
blocks.push("-- Seeder for the five text courses (Course 4 entrepreneurship already has content).");
blocks.push("");

for (const course of manifest.courses) {
  const dir = path.join(COURSES_ROOT, course.folder);
  const files = fs
    .readdirSync(dir)
    .filter((f) => f.toLowerCase().endsWith(".md"))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

  if (!files.length) {
    console.warn(`[warn] no markdown files in ${course.folder}`);
    continue;
  }

  const courseTitleCmt = `-- Course: ${course.title}`;
  const stmts = [];
  files.forEach((file, i) => {
    const raw = fs.readFileSync(path.join(dir, file), "utf8");
    const lines = raw.replace(/^\uFEFF/, "").split("\n");
    let title = file.replace(/\.md$/i, "").replace(/^\d+\s*[-._ ]?\s*/, "").trim();
    while (lines.length && lines[0].trim() === "") lines.shift();
    if (lines[0] && lines[0].startsWith("# ")) {
      title = lines[0].replace(/^#\s+/, "").trim();
      lines.shift();
    }
    const content = lines.join("\n").trim();
    const b64 = Buffer.from(content, "utf8").toString("base64");
    const words = content.split(/\s+/).length;
    const duration = estimateDuration(words);
    const sortOrder = i;

    stmts.push(`-- ${sortOrder}. ${title} (${duration} min, ${words} words)`);
    stmts.push(`insert into public.lessons (course_id, title, duration_min, content, sort_order)`);
    stmts.push(`select c.id, '${esc(title)}', ${duration}, convert_from(decode('${b64}','base64'),'utf8'), ${sortOrder}`);
    stmts.push(`from public.courses c where c.title = '${esc(course.title)}'`);
    stmts.push(`on conflict (course_id, sort_order) do update`);
    stmts.push(`set title = excluded.title, duration_min = excluded.duration_min, content = excluded.content;`);
    stmts.push("");
  });

  blocks.push(courseTitleCmt);
  blocks.push(...stmts);
}

const header = `-- 6-course text curriculum for the Learning Hub.
-- Sort orders 0..N create the course structure; conflict upserts make it re-runnable.
`;
fs.writeFileSync(OUT_FILE, header + "\n" + blocks.join("\n"), "utf8");
console.log(`Wrote ${OUT_FILE}`);
console.log(`Courses: ${manifest.courses.length}, Lessons: ${blocks.filter((b) => b.startsWith("-- ") && /min, \d+ words/.test(b)).length}`);